// Keep the game's field guide aligned with the site's authored trail.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('app.js', root), 'utf8');
const literals = source.slice(source.indexOf('  var TRAILHEADS'), source.indexOf('  var D ='));
const context = vm.createContext({});
vm.runInContext(literals, context, { timeout: 1000 });
const { TRAILHEADS, FACE_STOPS, RIDGE_STOPS, FALSE_SUMMIT, SUMMIT_STOP } = context;
const chapters = [{ id: 'trailhead-love', face: 'love', lap: 0, ...TRAILHEADS.love }];
for (let lap = 0; lap < 3; lap++) {
  for (const [key, face] of [['passion', 'love'], ['good', 'good'], ['profession', 'good'], ['paid', 'paid'], ['vocation', 'paid'], ['needs', 'needs'], ['mission', 'needs'], ['love', 'love']]) {
    chapters.push({ id: key + '-' + (lap + 1), face, lap: lap + 1, ...(FACE_STOPS[key] || RIDGE_STOPS[key])[lap] });
  }
}
chapters.push({ id: 'false-summit', face: 'summit', lap: 4, ...FALSE_SUMMIT }, { id: 'summit', face: 'summit', lap: 4, ...SUMMIT_STOP });
const output = '// Generated by scripts/build-game-data.mjs from app.js.\nexport const CHAPTERS = ' + JSON.stringify(chapters, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (await readFile(new URL('game/chapters.mjs', root), 'utf8') !== output) throw new Error('Run node scripts/build-game-data.mjs to refresh the game field guide.');
} else await writeFile(new URL('game/chapters.mjs', root), output);
